def cite(sid: str, page: int) -> str:
    con = sqlite3.connect(DB)
    row = con.execute(
        "SELECT printed_page FROM pages WHERE source_id=? AND pdf_page=?", (sid, page)
    ).fetchone()
    con.close()
    book = BOOKS[sid]
    title = book.get("short_title") or book["title"]
    if row and row[0] is not None:
        return f"《{title}》p.{row[0]}（PDF {page}）"
    return f"《{title}》PDF {page}"


